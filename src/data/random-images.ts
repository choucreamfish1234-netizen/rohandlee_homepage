function getPool(category?: string): string[] {
  if (!category) return Object.values(IMAGE_POOLS).flat()
  const keys = CATEGORY_TO_POOL[category]
  if (!keys) return Object.values(IMAGE_POOLS).flat()
  return keys.flatMap(k => IMAGE_POOLS[k])
}

export function getRandomImage(category?: string, usedUrls: string[] = []): string {
  const pool = getPool(category)
  const available = pool.filter(url => !usedUrls.includes(url))
  const source = available.length > 0 ? available : pool
  return source[Math.floor(Math.random() * source.length)]
}

export function getImagePool(category?: string): string[] {
  return getPool(category)
}
